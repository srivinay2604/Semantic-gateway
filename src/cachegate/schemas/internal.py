"""Internal data-transfer objects used between gateway layers.

These are NOT the same as the public OpenAI-compatible schemas in
``cachegate.schemas.openai``. The internal types decouple the provider
implementations from the public API surface.

Phase 1 fills: InternalRequest, InternalResponse.
Phase 2 adds: streaming fields.
Phase 4–5 adds: cache_result, cache_similarity fields used by headers.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Literal

from pydantic import BaseModel


class CacheResult(StrEnum):
    """Enum of possible cache outcomes, surfaced in X-Cache response header."""

    HIT_EXACT = "HIT-EXACT"
    HIT_SEMANTIC = "HIT-SEMANTIC"
    MISS = "MISS"
    BYPASS = "BYPASS"
    DISABLED = "DISABLED"


class InternalMessage(BaseModel):
    """Internal representation of a chat message."""

    role: Literal["system", "user", "assistant", "tool", "function"]
    content: str | None = None
    name: str | None = None


class InternalRequest(BaseModel):
    """Normalised, provider-agnostic chat completion request.

    Created from the validated ChatCompletionRequest in the route handler
    and passed to the provider router.
    """

    request_id: str
    """UUID assigned by request-ID middleware."""

    model_alias: str
    """The alias as submitted by the client (e.g. 'gpt-4o-mini')."""

    resolved_provider: str = ""
    """Set by the router after alias resolution (e.g. 'mock/echo')."""

    messages: list[InternalMessage]
    temperature: float | None = None
    top_p: float | None = None
    max_tokens: int | None = None
    stop: str | list[str] | None = None
    user: str | None = None


class InternalUsage(BaseModel):
    """Token usage counts."""

    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0


class InternalResponse(BaseModel):
    """Provider-agnostic chat completion response.

    Converted to ChatCompletionResponse before returning to the client.
    """

    response_id: str
    """ID assigned by provider or generated by mock."""

    model: str
    """Resolved model name (may differ from alias)."""

    content: str
    """Text of the completion."""

    finish_reason: Literal["stop", "length", "content_filter", "tool_calls"] = "stop"
    usage: InternalUsage

    # Populated after cache lookup (Phase 4+)
    cache_result: CacheResult = CacheResult.MISS
    cache_similarity: float | None = None

    # Latency bookkeeping
    provider_latency_ms: float = 0.0

    # Provider that served this response
    provider: str = "mock"

    @property
    def was_cache_hit(self) -> bool:
        return self.cache_result in (CacheResult.HIT_EXACT, CacheResult.HIT_SEMANTIC)
